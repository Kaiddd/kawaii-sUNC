  local gameObject
  gameObject = game
  return (gameObject:HttpGet("https://raw.githubusercontent.com/Kaiddd/kawaii-sUNC/main/" .. path))
end

function loadModule(path)
  local source, chunk, loadError
  source = fetchSource(path)
  chunk = loadstring
  chunk, loadError = chunk(source, "@" .. path)
  return (assert(chunk, loadError))
end

